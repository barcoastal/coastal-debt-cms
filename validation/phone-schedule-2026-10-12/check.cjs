const assert = require('node:assert/strict');
const model = require('../../public/assets/phone-schedule');
const inject = require('../../server/lib/phone-visibility');
const Database = require('better-sqlite3');
const express = require('express');
const createRouter = require('../../server/routes/phone-schedule');

const schedule = model.defaults(); schedule.mode = 'scheduled';
const visible = (date, config = schedule) => model.visible(config, Date.parse(date));
assert.equal(visible('2026-10-12T12:59:59Z'), false);
assert.equal(visible('2026-10-12T13:00:00Z'), true);
assert.equal(visible('2026-10-12T21:59:59Z'), true);
assert.equal(visible('2026-10-12T22:00:00Z'), false);
assert.equal(visible('2026-10-11T16:00:00Z'), false);
assert.equal(visible('2026-12-14T13:59:59Z'), false, 'winter offset');
assert.equal(visible('2026-12-14T14:00:00Z'), true);
const night = model.defaults(); night.mode = 'scheduled';
for (const day of model.days) night.days[day].mode = 'closed';
night.days.sun = {mode:'hours', start:'22:00', end:'02:00'};
assert.equal(visible('2026-10-12T01:59:59Z', night), false);
assert.equal(visible('2026-10-12T02:00:00Z', night), true);
assert.equal(visible('2026-10-12T05:59:59Z', night), true);
assert.equal(visible('2026-10-12T06:00:00Z', night), false);
const dst = model.defaults(); dst.mode = 'scheduled';
dst.days.sun = {mode:'hours', start:'01:00', end:'03:00'};
assert.equal(visible('2026-11-01T05:30:00Z', dst), true, 'first repeated 1:30');
assert.equal(visible('2026-11-01T06:30:00Z', dst), true, 'second repeated 1:30');
assert.equal(visible('2026-11-01T08:00:00Z', dst), false);
assert.equal(visible('2026-03-08T06:59:59Z', dst), true, 'spring jump');
assert.equal(visible('2026-03-08T07:00:00Z', dst), false);
dst.days.sun.mode = 'all-day';
assert.equal(visible('2026-11-01T04:00:00Z', dst), true, 'local midnight');
assert.equal(visible('2026-11-02T04:59:59Z', dst), true, '25 hour day');
dst.timezone = 'Asia/Kathmandu'; dst.days.mon = {mode:'hours',start:'09:00',end:'10:00'};
assert.equal(visible('2026-10-12T03:15:00Z', dst), true, 'non-whole-hour timezone');
assert.equal(visible('2026-10-12T04:15:00Z', dst), false);
assert.equal(visible('2026-10-11T16:00:00Z', model.defaults()), true, 'default is always show');
assert.equal(visible('2026-10-12T16:00:00Z', {...schedule, mode:'hidden'}), false);
for (const invalid of [{...schedule, mode:'bad'}, {...schedule, timezone:'bogus'}, {...schedule, days:{}}, {...schedule, days:{...schedule.days, mon:{mode:'hours',start:'24:30',end:'12:00'}}}, {...schedule, days:{...schedule.days, mon:{mode:'hours',start:'09:00',end:'09:00'}}}]) assert.throws(() => model.normalize(invalid));
assert.deepEqual(model.normalize({...schedule, secret:'discard'}), schedule);
assert.equal(inject(inject('<html><head></head><body></body></html>')), inject('<html><head></head><body></body></html>'));
console.log('PASS: timezones, DST, exact boundaries, weekends, overnight, all-day, validation and defaults.');

(async () => {
  const db = new Database(':memory:');
  db.exec('CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT); CREATE TABLE activity_logs (user_id INTEGER, user_name TEXT, action TEXT, entity_type TEXT, details TEXT, ip_address TEXT);');
  db.prepare('INSERT INTO settings VALUES (?, ?)').run('smtp_pass', 'never-public');
  const app = express(); app.use(express.json());
  const auth = (req, res, next) => {
    if (!req.headers['x-test-role']) return res.status(401).json({error:'Auth required'});
    req.user = {id:1, name:'Test admin', role:req.headers['x-test-role']}; next();
  };
  app.use('/api/phone-schedule', createRouter(db, auth));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const base = 'http://127.0.0.1:' + server.address().port + '/api/phone-schedule';
  try {
    const get = await fetch(base+'/public');
    assert.match(get.headers.get('cache-control'), /no-store/);
    assert.match(get.headers.get('cdn-cache-control'), /no-store/);
    const data = await get.json();
    assert.equal(data.schedule.mode, 'always');
    assert.deepEqual(Object.keys(data).sort(), ['schedule','serverTime']);
    assert.equal((await fetch(base)).status, 401);
    const put = role => fetch(base, {method:'PUT', headers:{'content-type':'application/json', ...(role ? {'x-test-role':role} : {})}, body:JSON.stringify(schedule)});
    assert.equal((await put()).status, 401);
    assert.equal((await put('editor')).status, 403);
    assert.equal((await put('admin')).status, 200);
    assert.deepEqual((await (await fetch(base+'/public')).json()).schedule, schedule);
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM activity_logs').get().n, 1);
    const bad = await fetch(base, {method:'PUT',headers:{'content-type':'application/json','x-test-role':'admin'},body:JSON.stringify({...schedule,timezone:'bad'})});
    assert.equal(bad.status,400);
    assert.deepEqual((await (await fetch(base+'/public')).json()).schedule, schedule, 'invalid save is atomic');
    const script = await (await fetch(base+'/runtime.js')).text();
    assert.ok(!script.includes('never-public'));
    assert.ok(script.includes('startCoastalPhoneVisibility('));
    new (require('node:vm').Script)(script);
    console.log('PASS: authenticated admin writes, persistence, validation, activity log, public isolation and uncached runtime.');
  } finally { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); db.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
